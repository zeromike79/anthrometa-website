let lang = localStorage.getItem('am-lang') || 'ko';

function setLang(l) {
  lang = l;
  localStorage.setItem('am-lang', l);
  document.documentElement.lang = {ko:'ko',en:'en',ja:'ja'}[l];
  document.body.className = 'lang-' + l;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (el.hasAttribute('data-notrans')) return;
    const v = T[l][el.getAttribute('data-i18n')];
    if (v != null) el.innerHTML = v;
  });
  ['ko','en','ja'].forEach(x => {
    const b = document.getElementById('b'+x);
    if (b) b.classList.toggle('active', x === l);
  });
}

/* Active nav */
function initNav() {
  const page = window.location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('a[data-page]').forEach(a => {
    const p = a.getAttribute('data-page');
    a.classList.toggle('active-link', p === page || (page === '' && p === 'index.html'));
  });
}

/* Header scroll */
window.addEventListener('scroll', () => {
  const h = document.getElementById('hdr');
  if (h) h.classList.toggle('scrolled', scrollY > 20);
});

/* Mobile menu */
function toggleMenu() {
  document.getElementById('mnav').classList.toggle('open');
  document.getElementById('burg').classList.toggle('open');
}
function closeMenu() {
  document.getElementById('mnav').classList.remove('open');
  document.getElementById('burg').classList.remove('open');
}

/* FAQ */
function toggleFaq(btn) {
  const item = btn.parentElement;
  const wasOpen = item.classList.contains('open');
  document.querySelectorAll('.fi').forEach(i => i.classList.remove('open'));
  if (!wasOpen) item.classList.add('open');
}

/* Scroll reveal */
function initReveal() {
  const obs = new IntersectionObserver(entries => {
    entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('vis'); });
  }, { threshold: 0.08, rootMargin: '0px 0px -40px 0px' });
  document.querySelectorAll('.reveal').forEach(el => obs.observe(el));
}

/* Init */
document.addEventListener('DOMContentLoaded', () => {
  setLang(lang);
  initNav();
  initReveal();
  // trigger scroll check for already-scrolled state on reload
  if (scrollY > 20) {
    const h = document.getElementById('hdr');
    if (h) h.classList.add('scrolled');
  }
});
